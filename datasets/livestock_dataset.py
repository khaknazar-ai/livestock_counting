"""
datasets/livestock_dataset.py

PyTorch Dataset for livestock density estimation.

Handles:
  - Train / val / test split (deterministic, seeded)
  - Images with point annotations (density map available → used for training)
  - Images with count-only annotations (no density map → used for test MAE only)
  - LabelMe JSON format converter (for annotations made with LabelMe tool)

File pairing convention:
  data/livestock/images/pen_001.jpg
  data/livestock/annotations/pen_001.json    ← point annotations
  data/livestock/density_maps/pen_001.npy    ← pre-generated by generate_density_map.py

Usage:
    from datasets.livestock_dataset import LivestockDataset, build_dataloaders
    from datasets.transforms import TrainTransforms, ValTransforms
    import yaml

    with open('configs/config.yaml') as f:
        cfg = yaml.safe_load(f)

    train_loader, val_loader, test_loader = build_dataloaders(cfg)
"""

import os
import json
import random
import numpy as np
import cv2
from PIL import Image
import torch
from torch.utils.data import Dataset, DataLoader
from pathlib import Path


# ─────────────────────────────────────────────
# Annotation helpers
# ─────────────────────────────────────────────

def load_annotation(ann_path: str) -> dict:
    """
    Load annotation JSON. Returns dict with keys:
      image_file (str), points (list of [x,y]), count (int)
    Handles both project format and LabelMe format.
    """
    with open(ann_path, 'r', encoding='utf-8') as f:
        ann = json.load(f)

    # --- Project native format ---
    if 'image_file' in ann:
        ann.setdefault('points', [])
        ann.setdefault('count', len(ann['points']))
        return ann

    # --- LabelMe format ---
    # LabelMe stores shapes as {"label": "animal", "points": [[x,y]], "shape_type": "point"}
    if 'shapes' in ann:
        image_file = os.path.basename(ann.get('imagePath', ''))
        points = []
        for shape in ann['shapes']:
            if shape.get('shape_type') == 'point':
                pts = shape['points']  # [[x, y]]
                points.append(pts[0])
        return {
            'image_file': image_file,
            'points':     points,
            'count':      len(points)
        }

    # --- Fallback: count-only format ---
    return {
        'image_file': ann.get('image_file', ''),
        'points':     [],
        'count':      ann.get('count', 0)
    }


# ─────────────────────────────────────────────
# Dataset split builder
# ─────────────────────────────────────────────

def build_splits(ann_dir: str,
                 train_ratio: float = 0.70,
                 val_ratio:   float = 0.15,
                 seed:        int   = 42,
                 den_dir:     str   = None) -> dict:
    """
    Deterministically split annotation files into train / val / test.

    Samples WITH point annotations (and density maps) → eligible for train/val/test.
    Samples with count-only annotations (no points) → test ONLY.
    This ensures training only uses samples with proper density supervision.

    Args:
        ann_dir:     Path to annotation JSON directory
        train_ratio: Fraction of point-annotated samples for training
        val_ratio:   Fraction of point-annotated samples for validation
        seed:        Random seed for reproducibility
        den_dir:     Path to density maps directory (if provided, used to verify
                     which samples actually have generated density maps)

    Returns:
        {'train': [...], 'val': [...], 'test': [...]}
        Each list contains annotation file stems (no extension).
    """
    ann_files = sorted([
        f.replace('.json', '')
        for f in os.listdir(ann_dir)
        if f.endswith('.json')
    ])

    # Separate: samples with point annotations vs count-only
    has_points = []
    count_only = []

    for stem in ann_files:
        ann_path = os.path.join(ann_dir, stem + '.json')
        ann = load_annotation(ann_path)

        # Check if sample has real point annotations
        has_pts = len(ann.get('points', [])) > 0

        # If den_dir provided, also check density map file exists
        if has_pts and den_dir:
            den_path = os.path.join(den_dir, stem + '.npy')
            has_pts = has_pts and os.path.exists(den_path)

        if has_pts:
            has_points.append(stem)
        else:
            count_only.append(stem)

    # Split point-annotated samples into train/val/test
    random.seed(seed)
    random.shuffle(has_points)

    n = len(has_points)
    n_train = int(n * train_ratio)
    n_val   = int(n * val_ratio)

    train_stems = has_points[:n_train]
    val_stems   = has_points[n_train:n_train + n_val]
    test_stems  = has_points[n_train + n_val:]

    # Count-only samples always go to test
    test_stems.extend(count_only)

    print(f"[Split] Point-annotated: {len(has_points)} "
          f"(train={len(train_stems)}, val={len(val_stems)}, "
          f"test_density={len(has_points) - n_train - n_val})")
    print(f"[Split] Count-only → test: {len(count_only)}")
    print(f"[Split] Total test: {len(test_stems)}")

    return {
        'train': train_stems,
        'val':   val_stems,
        'test':  test_stems,
    }


# ─────────────────────────────────────────────
# PyTorch Dataset
# ─────────────────────────────────────────────

class LivestockDataset(Dataset):
    """
    Dataset for dense livestock counting via density estimation.

    Each sample returns:
        image:   torch.Tensor [3, H, W]  (normalized)
        density: torch.Tensor [1, H, W]  (GT density map, sum = count)
        count:   float                   (GT animal count)
        name:    str                     (image stem, for logging)

    For samples without a density map (count-only), density is all zeros
    and the count is used only during evaluation (not for density loss).
    """

    def __init__(self,
                 stems:    list,
                 img_dir:  str,
                 ann_dir:  str,
                 den_dir:  str,
                 transform=None,
                 split:    str = 'train'):
        """
        Args:
            stems:     List of file stems (no extension) for this split
            img_dir:   Path to images directory
            ann_dir:   Path to annotations directory
            den_dir:   Path to density maps directory (.npy files)
            transform: Paired transform callable (image, density) → (image, density)
            split:     'train', 'val', or 'test' (for logging)
        """
        self.img_dir   = img_dir
        self.ann_dir   = ann_dir
        self.den_dir   = den_dir
        self.transform = transform
        self.split     = split

        # Resolve each stem to a valid (image_path, ann_path, den_path or None)
        self.samples = []
        skipped = 0

        for stem in stems:
            ann_path = os.path.join(ann_dir, stem + '.json')
            if not os.path.exists(ann_path):
                skipped += 1
                continue

            ann      = load_annotation(ann_path)
            img_file = ann.get('image_file', '')

            # Resolve image path
            img_path = self._find_image(img_dir, stem, img_file)
            if img_path is None:
                skipped += 1
                continue

            # Density map (optional — count-only samples won't have one)
            den_path = os.path.join(den_dir, stem + '.npy')
            has_density = os.path.exists(den_path)

            self.samples.append({
                'stem':        stem,
                'img_path':    img_path,
                'ann_path':    ann_path,
                'den_path':    den_path if has_density else None,
                'gt_count':    float(ann.get('count', 0)),
                'has_density': has_density,
            })

        if skipped > 0:
            print(f"[{split}] Warning: skipped {skipped} samples "
                  f"(missing image or annotation)")

    def _find_image(self, img_dir: str, stem: str, img_file: str):
        """Try multiple extensions to locate the image file."""
        # First try the filename recorded in annotation
        if img_file:
            candidate = os.path.join(img_dir, img_file)
            if os.path.exists(candidate):
                return candidate

        # Fall back to stem + common extensions
        for ext in ['.jpg', '.jpeg', '.png', '.JPG', '.JPEG', '.PNG']:
            candidate = os.path.join(img_dir, stem + ext)
            if os.path.exists(candidate):
                return candidate

        return None

    def __len__(self):
        return len(self.samples)

    def __getitem__(self, idx: int):
        s = self.samples[idx]

        # ── Load image ──────────────────────────────
        image = Image.open(s['img_path']).convert('RGB')

        # ── Load density map ────────────────────────
        if s['has_density']:
            density = np.load(s['den_path']).astype(np.float32)
        else:
            # Count-only sample: synthesize empty density map
            W, H = image.size
            density = np.zeros((H, W), dtype=np.float32)

        # ── Apply transforms ────────────────────────
        if self.transform is not None:
            image, density = self.transform(image, density)

        return {
            'image':       image,             # Tensor [3, H, W]
            'density':     density,           # Tensor [1, H, W]
            'count':       torch.tensor(s['gt_count'], dtype=torch.float32),
            'has_density': s['has_density'],  # bool: include in density loss?
            'name':        s['stem'],
            'path':        s['img_path'],     # str: original image path (for YOLO eval)
        }

    def summary(self):
        n_density   = sum(s['has_density'] for s in self.samples)
        n_countonly = len(self.samples) - n_density
        counts      = [s['gt_count'] for s in self.samples]
        if len(counts) == 0:
            print(f"  [{self.split}] Total=0 (empty)")
            return
        print(f"  [{self.split}] Total={len(self.samples)} | "
              f"w/ density map={n_density} | "
              f"count-only={n_countonly} | "
              f"count range=[{min(counts):.0f}, {max(counts):.0f}]")


# ─────────────────────────────────────────────
# DataLoader builder
# ─────────────────────────────────────────────

def build_dataloaders(cfg: dict):
    """
    Build train/val/test DataLoaders from config.yaml.

    Args:
        cfg: parsed config.yaml dict

    Returns:
        (train_loader, val_loader, test_loader)
    """
    from datasets.transforms import TrainTransforms, ValTransforms

    paths      = cfg['paths']
    ds_cfg     = cfg['dataset']
    train_cfg  = cfg['train']
    hw_cfg     = cfg['hardware']

    input_size = tuple(train_cfg['input_size'])   # (H, W)

    # Build splits
    splits = build_splits(
        ann_dir     = paths['annotation_dir'],
        train_ratio = ds_cfg['train_ratio'],
        val_ratio   = ds_cfg['val_ratio'],
        seed        = ds_cfg['seed'],
        den_dir     = paths['density_map_dir']
    )

    train_ds = LivestockDataset(
        stems     = splits['train'],
        img_dir   = paths['image_dir'],
        ann_dir   = paths['annotation_dir'],
        den_dir   = paths['density_map_dir'],
        transform = TrainTransforms(input_size),
        split     = 'train'
    )
    val_ds = LivestockDataset(
        stems     = splits['val'],
        img_dir   = paths['image_dir'],
        ann_dir   = paths['annotation_dir'],
        den_dir   = paths['density_map_dir'],
        transform = ValTransforms(input_size),
        split     = 'val'
    )
    test_ds = LivestockDataset(
        stems     = splits['test'],
        img_dir   = paths['image_dir'],
        ann_dir   = paths['annotation_dir'],
        den_dir   = paths['density_map_dir'],
        transform = ValTransforms(input_size),
        split     = 'test'
    )

    print("Dataset splits:")
    train_ds.summary()
    val_ds.summary()
    test_ds.summary()

    train_loader = DataLoader(
        train_ds,
        batch_size  = train_cfg['batch_size'],
        shuffle     = True,
        num_workers = hw_cfg['num_workers'],
        pin_memory  = True,
        drop_last   = True    # Avoid batch-size-1 edge cases with BatchNorm
    )
    val_loader = DataLoader(
        val_ds,
        batch_size  = cfg['eval']['batch_size'],
        shuffle     = False,
        num_workers = hw_cfg['num_workers'],
        pin_memory  = True,
    )
    test_loader = DataLoader(
        test_ds,
        batch_size  = cfg['eval']['batch_size'],
        shuffle     = False,
        num_workers = hw_cfg['num_workers'],
        pin_memory  = True,
    )

    return train_loader, val_loader, test_loader
